"""Builds docs/design/rulebook.html: rulebook.md and deviations.md chapters merged into the live specimen
(rulebook-specimen.html) with a navigation sidebar. Run from anywhere: python3 docs/design/build_rulebook.py"""
import html, re
from pathlib import Path
import markdown

here = Path(__file__).resolve().parent
tpl = (here / "rulebook-specimen.html").read_text()


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def chapters(md, key_of):
    out = {}
    for part in re.split(r"^## ", md, flags=re.M)[1:]:
        title, body = part.split("\n", 1)
        key = key_of(title)
        out[key] = (title.strip(), body)
    return out


def render(key, title, body):
    sid = f"ch-{key}"
    subs = []

    def h3(m):
        inner = m.group(1).strip()
        t = html.unescape(re.sub(r"<.*?>", "", inner))
        hid = f"{sid}-{slug(t)}"
        subs.append((hid, t))
        return f'<h3 id="{hid}">{inner}</h3>'

    body_html = markdown.markdown(body, extensions=["tables"])
    body_html = re.sub(r"<h3>(.*?)</h3>", lambda m: h3(m), body_html)
    return f'<section class="doc" id="{sid}"><h2>{html.escape(title)}</h2>\n{body_html}\n</section>', subs


rb = (here / "rulebook.md").read_text()
dv = (here / "deviations.md").read_text()
chs = chapters(rb, lambda t: t.split(".", 1)[0].strip())
dv_body = dv.split("\n", 1)[1]
chs["D"] = ("Deviations from the rulebook", dv_body.replace("\n## ", "\n### "))

pre = rb.split("\n## ", 1)[0]
cover_title, cover_body = pre.split("\n", 1)
cover = f'<section class="doc cover" id="ch-cover"><h1>{html.escape(cover_title.lstrip("# ").strip())}</h1>\n{markdown.markdown(cover_body)}\n</section>'
tpl = tpl.replace("<!--COVER-->", cover, 1)
nav0 = ['<a href="#ch-cover" data-ch="cover"><i></i>Overview</a>']
nav, order = [], re.findall(r"<!--CH:(\w+)-->|<section class=\"demo\">\s*<div class=\"eyebrow\">(.*?)</div>\s*<h2>(.*?)</h2>", tpl)
demo_n, current = 0, None
for ch, eyebrow, h2 in order:
    if ch:
        current = ch
        title, body = chs[ch]
        sec, subs = render(ch, title, body)
        tpl = tpl.replace(f"<!--CH:{ch}-->", sec, 1)
        if ch == "D":
            nav.append('<div class="grp">Map</div>')
        elif ch == "0":
            nav.append('<div class="grp">Rulebook</div>')
        num = "" if ch == "D" else ch
        name = re.sub(r"^\d+\.\s*", "", title)
        nav.append(f'<a href="#ch-{ch}" data-ch="{ch}"><i>{num}</i>{html.escape(name)}</a>')
        nav += [f'<a class="sub" href="#{hid}" data-ch="{ch}">{html.escape(t)}</a>' for hid, t in subs]
    else:
        demo_n += 1
        did = f"demo-{demo_n}"
        tpl = tpl.replace('<section class="demo">', f'<section class="demo" id="{did}" data-done>', 1)
        nav.append(f'<a class="sub" href="#{did}" data-ch="{current}">Live: {html.escape(h2)}</a>')

tpl = tpl.replace(" data-done>", ">").replace("<!--NAV-->", "\n".join(nav0 + nav), 1)
tpl = re.sub(r"<!-- Template for docs/design/rulebook.html.*?-->", "<!-- Generated by docs/design/build_rulebook.py from rulebook.md, deviations.md and rulebook-specimen.html. Do not edit. -->", tpl, count=1, flags=re.S)
(here / "rulebook.html").write_text(tpl)
print(f"rulebook.html: {len(chs)} chapters, {demo_n} live sections")
