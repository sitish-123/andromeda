    // Decodes one UTF-8 sequence at text[i]; a malformed byte comes back as itself, one byte long.
    char32_t decode(std::string_view text, std::size_t i, std::size_t& length) {
      const auto b = static_cast<unsigned char>(text[i]);
      const std::size_t n = b < 0xC0 ? 1 : (b < 0xE0 ? 2 : (b < 0xF0 ? 3 : 4));
      if (n == 1 || i + n > text.size()) {
        length = 1;
        return b;
      }
      char32_t cp = b & (0xFF >> (n + 1));
      for (std::size_t k = 1; k < n; ++k) {
        const auto c = static_cast<unsigned char>(text[i + k]);
        if ((c & 0xC0) != 0x80) {
          length = 1;
          return b;
        }
        cp = (cp << 6) | (c & 0x3F);
      }
      length = n;
      return cp;
    }
