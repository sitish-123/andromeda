  std::string foldName(std::string_view text) {
    std::string out;
    out.reserve(text.size());
    for (std::size_t i = 0; i < text.size();) {
      const auto b = static_cast<unsigned char>(text[i]);
      if (b < 0x80) {
        out += static_cast<char>(b >= 'A' && b <= 'Z' ? b + ('a' - 'A') : b);
        ++i;
        continue;
      }
      std::size_t length = 1;
      const char32_t cp = decode(text, i, length);
      const auto* fold = std::ranges::lower_bound(kFolds, cp, {}, &Fold::from);
      if (fold != std::end(kFolds) && fold->from == cp) {
        out += fold->to;
      } else {
        out.append(text.substr(i, length));
      }
      i += length;
    }
    return out;
  }

