//! Turns one imported profile into a `PipeWire` filter-chain config:
//! speaker EQ (`param_eq`) → bass → leveler → limiter (andromeda-dsp); without
//! an imported profile only bass → limiter.

use std::f64::consts::PI;
use std::fmt::Write as _;

use anyhow::{Context, Result};

use crate::{PeqFilter, Profile, Tuning};

pub const SINK_NAME: &str = "andromeda_speakers";
/// Above the internal speaker sink (1009 on SOF/UCM), below headphones and HDMI picked by the user.
pub const SINK_PRIORITY: u32 = 1010;
const FS: f64 = 48_000.0;
const DAX: f64 = 16.0;

pub struct Settings<'a> {
    pub profile: &'a str,
    pub dsp_path: &'a str,
    /// `node.name` of the hardware speaker sink.
    pub target: &'a str,
    /// Gain into the final limiter; louder, peaks stay at the ceiling.
    pub loudness_db: f32,
    /// Virtual bass 0..10; above 0 also high-passes what the speaker cannot play.
    pub bass: f32,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Band {
    pub kind: &'static str,
    pub freq: f64,
    pub q: f64,
    pub gain_db: f64,
}

/// Profile name written for a speaker with no imported tuning: bass, loudness and limiter only.
pub const GENERIC: &str = "generic";

/// One chain node: its config text and its stereo input/output port names.
struct Node {
    name: &'static str,
    text: String,
    ports: (&'static str, &'static str),
}

#[allow(clippy::too_many_lines)]
pub fn filter_chain_conf(t: Option<&Tuning>, s: &Settings) -> Result<String> {
    let dsp = s.dsp_path;
    let ladspa = |name: &'static str, label: &str, control: String| Node {
        name,
        text: format!(
            "{{ type = ladspa name = {name} plugin = \"{dsp}\" label = {label}\n            control = {{{control} }} }}"
        ),
        ports: ("L", "R"),
    };
    let highpass = if s.bass > 0.0 { 60.0 } else { 0.0 };
    let bass = ladspa("vb", "bass", format!(" \"Amount\" = {:.1} \"Highpass\" = {highpass:.1}", s.bass));
    let limiter = ladspa(
        "lim",
        "limiter",
        format!(" \"Input gain\" = {:.1} \"Ceiling\" = -1.0 \"Release\" = 80.0", s.loudness_db),
    );
    let (source, nodes) = match t {
        None => (GENERIC.to_owned(), vec![bass, limiter]),
        Some(t) => {
            let ep =
                t.endpoints.iter().find(|e| e.kind == "internal_speaker").context("no internal_speaker endpoint")?;
            let p = ep.profiles.get(s.profile).with_context(|| format!("no profile {:?}", s.profile))?;
            let mut eq = String::new();
            for ch in 0..2 {
                let _ = write!(eq, "\n              filters{} = [", ch + 1);
                for b in channel_eq(t, p, ch) {
                    let _ = write!(
                        eq,
                        "\n                {{ type = {} freq = {:.1} q = {:.4} gain = {:.3} }}",
                        b.kind, b.freq, b.q, b.gain_db
                    );
                }
                eq.push_str("\n              ]");
            }
            let cp = |k: &str| p.cp.get(k).and_then(|v| v.first()).copied().unwrap_or(0.0);
            let leveler_amount = if cp("volume-leveler-enable") > 0.0 { cp("volume-leveler-amount") } else { 0.0 };
            let leveler_target =
                p.cp.get("volume-leveler-in-target").and_then(|v| v.first()).map_or(-20.0, |v| v / DAX);
            let eq = Node {
                name: "eq",
                text: format!(
                    "{{ type = builtin name = eq label = param_eq\n            config = {{{eq}\n            }}\n          }}"
                ),
                ports: ("1", "2"),
            };
            let lev = ladspa(
                "lev",
                "leveler",
                format!(" \"Target\" = {leveler_target:.2} \"Amount\" = {leveler_amount:.1} \"Max gain\" = 6.0"),
            );
            (
                format!("{} profile \"{}\" (tuned {})", t.subsystem, s.profile, t.tuning_date),
                vec![eq, bass, lev, limiter],
            )
        }
    };
    let port =
        |n: &Node, dir: &str, ch: usize| format!("{}:{dir} {}", n.name, if ch == 0 { n.ports.0 } else { n.ports.1 });
    let node_text: Vec<&str> = nodes.iter().map(|n| n.text.as_str()).collect();
    let mut links = String::new();
    for w in nodes.windows(2) {
        for ch in 0..2 {
            let _ = write!(
                links,
                "\n          {{ output = \"{}\" input = \"{}\" }}",
                port(&w[0], "Out", ch),
                port(&w[1], "In", ch)
            );
        }
    }
    let (first, last) = (&nodes[0], &nodes[nodes.len() - 1]);
    Ok(format!(
        r#"# Generated by andromeda-sound: profile "{profile}" loudness {loudness} bass {bass}; source {source}. Do not edit.
context.modules = [
  {{ name = libpipewire-module-filter-chain
    args = {{
      node.description = "Speakers"
      media.name = "Speakers"
      filter.graph = {{
        nodes = [
          {nodes}
        ]
        links = [{links}
        ]
        inputs = [ "{in0}" "{in1}" ]
        outputs = [ "{out0}" "{out1}" ]
      }}
      audio.rate = 48000
      audio.channels = 2
      audio.position = [ FL FR ]
      capture.props = {{ node.name = "{SINK_NAME}" andromeda.enhances = "{target}" media.class = Audio/Sink priority.session = {SINK_PRIORITY} priority.driver = {SINK_PRIORITY} device.icon-name = "audio-speakers" }}
      playback.props = {{ node.name = "{SINK_NAME}.out" node.passive = true target.object = "{target}" node.dont-reconnect = true stream.dont-remix = true }}
    }}
  }}
]
"#,
        profile = if t.is_some() { s.profile } else { GENERIC },
        loudness = s.loudness_db,
        bass = s.bass,
        nodes = node_text.join("\n          "),
        in0 = port(first, "In", 0),
        in1 = port(first, "In", 1),
        out0 = port(last, "Out", 0),
        out1 = port(last, "Out", 1),
        target = s.target,
    ))
}

/// Target curve in dB at the 20 band centres for one channel.
pub fn channel_curve(p: &Profile, ch: usize) -> Vec<f64> {
    let mut curve = vec![0.0; 20];
    let mut add = |map: &std::collections::BTreeMap<String, Vec<f64>>, enable: &str, key: &str| {
        if map.get(enable).and_then(|v| v.first()).is_some_and(|&e| e > 0.0)
            && let Some(v) = map.get(key)
        {
            curve.iter_mut().zip(v).for_each(|(c, x)| *c += x / DAX);
        }
    };
    let opt = format!("audio-optimizer-bands.ch_{ch:02}");
    add(&p.vlldp, "audio-optimizer-enable", &opt);
    add(&p.cp, "audio-optimizer-enable", &opt);
    add(&p.cp, "graphic-equalizer-enable", "graphic-equalizer-bands");
    curve
}

/// Peaking bands at the band centres whose combined response fits the curve (interpolated
/// linearly in log frequency) on a dense grid, then the enabled speaker PEQ filters for this channel.
pub fn channel_eq(t: &Tuning, p: &Profile, ch: usize) -> Vec<Band> {
    let curve = channel_curve(p, ch);
    let centres = &t.band_freqs_hz;
    // Fit bands at the centres and their geometric midpoints: a sum of smooth bells
    // cannot follow the curve's kinks with the 20 centres alone.
    let freqs: Vec<f64> = centres
        .iter()
        .zip(centres.iter().skip(1).map(Some).chain([None]))
        .flat_map(|(&a, b)| [Some(a), b.map(|&b| (a * b).sqrt())])
        .flatten()
        .collect();
    let n = freqs.len();
    // Broad bells (0.3 x crossing Q) fit best: worst 0.66 dB on the UX3405CA curve; narrower ones ripple.
    let qs: Vec<f64> = (0..n).map(|i| 0.3 * band_q(&freqs, i)).collect();
    let grid: Vec<f64> =
        (0..GRID).map(|k| 60.0 * (20_000f64 / 60.0).powf(f64::from(k) / f64::from(GRID - 1))).collect();
    let target: Vec<f64> = grid.iter().map(|&f| interp_log(centres, &curve, f)).collect();
    let mut gains: Vec<f64> = freqs.iter().map(|&f| interp_log(centres, &curve, f)).collect();
    for _ in 0..10 {
        let jac: Vec<Vec<f64>> = grid
            .iter()
            .map(|&f| {
                (0..n)
                    .map(|j| {
                        peaking_db(freqs[j], qs[j], gains[j] + 0.5, f) - peaking_db(freqs[j], qs[j], gains[j] - 0.5, f)
                    })
                    .collect()
            })
            .collect();
        let res: Vec<f64> = grid
            .iter()
            .zip(&target)
            .map(|(&f, want)| want - (0..n).map(|j| peaking_db(freqs[j], qs[j], gains[j], f)).sum::<f64>())
            .collect();
        let mut a = vec![vec![0.0; n + 1]; n];
        for (i, row) in a.iter_mut().enumerate() {
            for j in 0..n {
                row[j] = jac.iter().map(|r| r[i] * r[j]).sum::<f64>() + if i == j { 1e-3 } else { 0.0 };
            }
            row[n] = jac.iter().zip(&res).map(|(r, e)| r[i] * e).sum();
        }
        for (g, d) in gains.iter_mut().zip(solve(a)) {
            *g = (*g + d).clamp(-24.0, 24.0);
        }
    }
    let mut bands: Vec<Band> = (0..freqs.len())
        .filter(|&i| gains[i].abs() > 0.01)
        .map(|i| Band { kind: "bq_peaking", freq: freqs[i], q: qs[i], gain_db: gains[i] })
        .collect();
    let ch_u32 = u32::try_from(ch).unwrap_or(u32::MAX);
    bands.extend(p.speaker_peq.iter().filter(|f| f.speaker == ch_u32).filter_map(peq_band));
    bands
}

const GRID: u32 = 400;

fn interp_log(xs: &[f64], ys: &[f64], x: f64) -> f64 {
    let i = xs.partition_point(|&v| v < x);
    if i == 0 {
        return ys[0];
    }
    if i >= xs.len() {
        return ys[xs.len() - 1];
    }
    let w = (x / xs[i - 1]).ln() / (xs[i] / xs[i - 1]).ln();
    ys[i - 1] + w * (ys[i] - ys[i - 1])
}

/// Gaussian elimination with partial pivoting on an augmented `n × (n+1)` matrix.
fn solve(mut a: Vec<Vec<f64>>) -> Vec<f64> {
    let n = a.len();
    for c in 0..n {
        let piv = (c..n).max_by(|&x, &y| a[x][c].abs().total_cmp(&a[y][c].abs())).unwrap_or(c);
        a.swap(c, piv);
        for r in c + 1..n {
            let f = a[r][c] / a[c][c];
            let (top, bottom) = a.split_at_mut(r);
            for (x, y) in bottom[0][c..].iter_mut().zip(&top[c][c..]) {
                *x -= f * y;
            }
        }
    }
    let mut x = vec![0.0; n];
    for r in (0..n).rev() {
        x[r] = (a[r][n] - (r + 1..n).map(|k| a[r][k] * x[k]).sum::<f64>()) / a[r][r];
    }
    x
}

/// DAX3 PEQ type codes, read from the files: 1 carries `q` (peaking), 2 and 3 carry `s` (shelves).
fn peq_band(f: &PeqFilter) -> Option<Band> {
    let (kind, q) = match f.kind {
        1 => ("bq_peaking", f.q?),
        2 => ("bq_lowshelf", shelf_q(f.gain_db, f.slope?)),
        3 => ("bq_highshelf", shelf_q(f.gain_db, f.slope?)),
        _ => return None,
    };
    Some(Band { kind, freq: f.freq_hz, q, gain_db: f.gain_db })
}

fn shelf_q(gain_db: f64, slope: f64) -> f64 {
    let a = 10f64.powf(gain_db / 40.0);
    1.0 / ((a + 1.0 / a) * (1.0 / slope - 1.0) + 2.0).sqrt()
}

/// Q that makes neighbouring bands cross near their -3 dB points.
fn band_q(freqs: &[f64], i: usize) -> f64 {
    let n = freqs.len();
    let f = freqs[i];
    let lo = if i > 0 { freqs[i - 1] } else { f * f / freqs[1] };
    let hi = if i + 1 < n { freqs[i + 1] } else { f * f / freqs[n - 2] };
    let bw = 2f64.powf((hi / lo).log2() / 2.0);
    bw.sqrt() / (bw - 1.0)
}

/// Magnitude in dB of an RBJ peaking biquad at 48 kHz, evaluated at `at` Hz.
pub fn peaking_db(f0: f64, q: f64, gain_db: f64, at: f64) -> f64 {
    let a = 10f64.powf(gain_db / 40.0);
    let w0 = 2.0 * PI * f0 / FS;
    let alpha = w0.sin() / (2.0 * q);
    let (b0, b1, b2) = (1.0 + alpha * a, -2.0 * w0.cos(), 1.0 - alpha * a);
    let (a0, a1, a2) = (1.0 + alpha / a, -2.0 * w0.cos(), 1.0 - alpha / a);
    let w = 2.0 * PI * at / FS;
    let mag2 = |c0: f64, c1: f64, c2: f64| {
        let re = c0 + c1 * w.cos() + c2 * (2.0 * w).cos();
        let im = -c1 * w.sin() - c2 * (2.0 * w).sin();
        re * re + im * im
    };
    10.0 * (mag2(b0, b1, b2) / mag2(a0, a1, a2)).log10()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Endpoint;

    #[test]
    fn fitted_eq_hits_curve_at_band_centres() {
        let freqs = vec![
            47., 141., 234., 328., 469., 656., 844., 1031., 1313., 1688., 2250., 3000., 3750., 4688., 5813., 7125.,
            9000., 11250., 13875., 19688.,
        ];
        let curve =
            vec![0., 0., 96., 0., -64., -48., 0., -32., -64., -32., 0., 0., 0., 0., 32., 48., 128., 192., 198., 211.];
        let mut p = Profile::default();
        p.vlldp.insert("audio-optimizer-enable".into(), vec![1.0]);
        p.vlldp.insert("audio-optimizer-bands.ch_00".into(), curve.clone());
        let t = Tuning {
            subsystem: String::new(),
            tuning_date: String::new(),
            band_freqs_hz: freqs.clone(),
            endpoints: vec![Endpoint {
                kind: "internal_speaker".into(),
                channels: 2,
                profiles: [("music".into(), p)].into(),
            }],
        };
        let bands = channel_eq(&t, &t.endpoints[0].profiles["music"], 0);
        let db: Vec<f64> = curve.iter().map(|v| v / 16.0).collect();
        for k in 0..200 {
            let f = 100.0 * 160f64.powf(f64::from(k) / 199.0);
            let resp: f64 = bands.iter().map(|b| peaking_db(b.freq, b.q, b.gain_db, f)).sum();
            let want = interp_log(&freqs, &db, f);
            assert!((resp - want).abs() < 1.0, "{f:.0} Hz: {resp:.2} dB, want {want:.2}");
        }
    }
}
